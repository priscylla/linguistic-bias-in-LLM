"""
scripts/make_review_doc.py
Gera os documentos de revisão a partir de config/*.yaml:

    reports/phase1_review.md   fatos, candidatos, stakes, nomes e
                               indicadores por idioma, com as notas do que
                               precisa de verificação
    reports/prompts_review.md  todos os prompts, por fato e idioma, com
                               as marcações (article_blocked, slot_case),
                               os prompts neutros da linha de base e as
                               palavras do teste do confundidor de artigo

    python scripts/make_review_doc.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from config.loader import (  # noqa: E402
    load_baseline, load_behavioral, load_experiment, load_facts, load_forcing, load_prompts,
    prompts_for,
)

OUT_FACTS   = ROOT / "reports" / "phase1_review.md"
OUT_PROMPTS = ROOT / "reports" / "prompts_review.md"
OUT_BEHAV   = ROOT / "reports" / "behavioral_review.md"
OUT_PENDING = ROOT / "reports" / "review_pt_en_and_support.md"

# Prompts confirmados na Fase 0 (paráfrase 1 de F1–F3, aviao/telefone, pt e it;
# reports/verified_values.md). O resto de PT e EN segue proposed.
CONFIRMED_P0 = {(f, l, t, 1) for f in ("aviao", "telefone") for l in ("pt", "it")
                for t in ("F1", "F2", "F3")}
TYPE_ORDER = ["F1", "F2", "F3", "QA", "place", "artifact"]
TYPE_LABEL = {"F1": "completion F1 (direct)", "F2": "completion F2 (attributive)",
              "F3": "completion F3 (disputative)", "QA": "QA (chat template)",
              "place": "place (indicator)", "artifact": "artifact (indicator)"}


def _names_cell(c, lang):
    by_case = c.names[lang]
    if list(by_case) == ["nom"]:
        return ", ".join(by_case["nom"])
    return "<br>".join(f"{case}: {', '.join(v)}" for case, v in by_case.items())


def facts_doc(exp, facts) -> str:
    langs = exp["languages"]
    out = [
        "# Phase 1 review: facts, candidates, names, indicators",
        "",
        "Generated by `scripts/make_review_doc.py` from `config/facts.yaml`. "
        "Edit the YAML, not this file. Runs refuse facts that are not `status: confirmed`. "
        "Confirmed values are logged in `reports/verified_values.md`.",
        "",
        "Single names are the unit of measurement (one next-token distribution per position). "
        "Indicators are artifact names and places, no dates. Place and artifact prompts run "
        "only where at least two candidates have indicators (and, per tokenizer, valid tokens; "
        "see `reports/tokenization_summary.md`).",
        "",
    ]
    for key, f in facts.items():
        out += [f"## `{key}` ({f.kind}, verb: {f.verb}, status: {f.status})", ""]
        out += ["| Candidate | Dominant | Stakes |", "| --- | --- | --- |"]
        for c in f.candidates:
            st = ", ".join(f"{s.language} {s.type}" for s in c.stakes) or "—"
            out.append(f"| {c.label} (`{c.id}`) | {'yes' if c.dominant else ''} | {st} |")
        out += ["", "**Names**", "", "| Candidate | " + " | ".join(langs) + " |",
                "| --- |" + " --- |" * len(langs)]
        for c in f.candidates:
            out.append(f"| `{c.id}` | " + " | ".join(_names_cell(c, l) for l in langs) + " |")
        for t in f.indicator_types():
            out += ["", f"**Indicators: {t}**", "", "| Candidate | " + " | ".join(langs) + " |",
                    "| --- |" + " --- |" * len(langs)]
            for c in f.candidates:
                if c.indicators.get(t):
                    out.append(f"| `{c.id}` | " + " | ".join(
                        ", ".join(c.indicators_for(t, l)) for l in langs) + " |")
        notes = [(c.id, n) for c in f.candidates for n in c.notes]
        if notes:
            out += ["", "**Notes**", ""] + [f"- `{cid}`: {n}" for cid, n in notes]
        out += [""]
    return "\n".join(out)


def _prompt_line(p) -> str:
    marks = (" ⛔" if p.article_blocked else "") + \
            (f" [{p.slot_case}]" if p.slot_case != "nom" else "")
    return f"- {p.type}.{p.paraphrase}: {p.text}{marks}"


def baseline_doc(exp, baseline) -> list:
    out = [
        "## Neutral baseline (`config/baseline_prompts.yaml`)",
        "",
        f"Status: `{baseline.status}`. Paraphrase *i* of each type mirrors paraphrase *i* of "
        "the real prompts in the same language (same slot ending, Russian case and ⛔ flag; "
        "the validator checks this). Topics: names = *the novel / its author*, "
        "place = *the bridge*, artifact = *the first ship*.",
        "",
    ]
    for lang in exp["languages"]:
        ps = prompts_for(baseline.prompts, None, lang)
        if not ps:
            continue
        flag = " (native review pending)" if ps[0].needs_native_review else ""
        out += [f"### {lang}{flag}", ""] + [_prompt_line(p) for p in ps] + [""]
    return out


def forcing_doc(exp, forcing) -> list:
    out = [
        "## Article-confound forcing words (`config/forcing.yaml`)",
        "",
        f"Status: `{forcing.status}`. **Articles** trigger the test when the final layer's top "
        "token is one of them; the word is appended and the candidates are measured at the next "
        "position. **Plural nouns** also trigger it, and are forced as a second step when they "
        "follow a forced article (*os → irmãos*). **Contractions** replace the final preposition "
        "of ⛔ prompts, one pass per form.",
        "",
        "| Language | Articles | Plural nouns | Contractions |",
        "| --- | --- | --- | --- |",
    ]
    for lang in exp["languages"]:
        plural = forcing.plural_nouns.get(lang, {})
        pl = ", ".join(plural.get("nom", [])) if list(plural) == ["nom"] else \
            "<br>".join(f"{c}: {', '.join(v)}" for c, v in plural.items())
        co = "<br>".join(f"{k} → {', '.join(v)}" for k, v in forcing.contractions.get(lang, {}).items())
        out.append(f"| {lang} | {', '.join(forcing.articles.get(lang, [])) or '—'} | "
                   f"{pl or '—'} | {co or '—'} |")
    return out + [""]


def prompts_doc(exp, facts, prompts, baseline=None, forcing=None) -> str:
    out = [
        "# Prompt review",
        "",
        "Generated from `config/prompts.yaml` (edit the YAML). Three paraphrases per type. "
        "Paraphrase 1 of F1–F3 for `aviao`/`telefone` in pt/en/de/it is the old prompt.",
        "",
        "- **⛔ article_blocked**: the slot ends in a preposition that contracts with an article "
        "(pt *por/em*, it *da/a*, fr *à*), so a candidate with an article (*os irmãos Wright*) "
        "cannot follow directly.",
        "- Native review: " + ", ".join(exp["native_review_languages"]) + " reviewed by native "
        "speakers (2026-10-29); a block still under review shows *(native review pending)*.",
        "",
    ]
    for key in facts:
        out += [f"## `{key}`", ""]
        for lang in exp["languages"]:
            ps = prompts_for(prompts, key, lang)
            if not ps:
                continue
            flag = " (native review pending)" if ps[0].needs_native_review else ""
            out += [f"### {lang}{flag}", ""]
            out += [_prompt_line(p) for p in ps] + [""]
    if baseline is not None:
        out += baseline_doc(exp, baseline)
    if forcing is not None:
        out += forcing_doc(exp, forcing)
    return "\n".join(out)


def behavioral_doc(exp, facts, b) -> str:
    out = [
        "# Behavioral extraction review: surface forms",
        "",
        f"Generated from `config/behavioral.yaml` (edit the YAML). Status: `{b.status}`. "
        "Extraction refuses to run until it is confirmed.",
        "",
        "A candidate is mentioned when any of its forms appears as a whole word, ignoring case and "
        "accents, in an answer in any language. **Excluded** forms don't count on their own in answers in that language (common "
        "words); longer forms containing them still count. First names alone never count.",
        "",
        "| Fact | Candidate | Forms | Excluded |",
        "| --- | --- | --- | --- |",
    ]
    for key, f in facts.items():
        for c in f.candidates:
            spec = b.forms.get(key, {}).get(c.id, {})
            ex = "<br>".join(f"{l}: {', '.join(v)}" for l, v in (spec.get("exclude") or {}).items())
            out.append(f"| `{key}` | {c.label} | {', '.join(spec.get('latin') or [])} | {ex or '—'} |")
    g = b.generation
    out += ["", "## Generation", "",
            f"Instruct models, QA prompts: {g['greedy']} greedy + {g['samples']} samples at "
            f"T={g['temperature']} (top_p={g['top_p']}, top_k={g['top_k']}, repetition penalty "
            f"{g['repetition_penalty']}; the models' own decoding defaults are overridden), "
            f"max_new_tokens={g['max_new_tokens']}.", ""]
    return "\n".join(out)


def pending_doc(exp, facts, prompts, baseline, forcing, behavioral) -> str:
    """Tudo o que segue proposed: prompts PT/EN, linha de base, forcing, formas de superfície."""
    langs = exp["languages"]
    out = [
        "# Still proposed: PT/EN prompts, baseline, forcing words, surface forms",
        "",
        "Generated by `scripts/make_review_doc.py` from the YAML files (edit the YAML, not this file). "
        "Every item below is still `proposed`. Each line has an ID to refer to it "
        "(`fact.lang.type.paraphrase`). ⛔ = the slot ends in a preposition that contracts with an "
        "article (`article_blocked`).",
        "",
        "Already confirmed and not listed: paraphrase 1 of F1–F3 for `aviao` and `telefone` in PT "
        "(Phase 0, `reports/verified_values.md`); all FR, DE and IT prompts in `config/prompts.yaml` "
        "(native speakers, 2026-10-29); the facts in `config/facts.yaml`.",
        "",
        "## a. PT and EN prompts (`config/prompts.yaml`)",
        "",
    ]
    n_a = 0
    for key, f in facts.items():
        out += [f"### `{key}` ({f.kind})", ""]
        for t in TYPE_ORDER:
            items = [p for p in prompts if p.fact == key and p.type == t and p.lang in ("pt", "en")
                     and (p.fact, p.lang, p.type, p.paraphrase) not in CONFIRMED_P0]
            if not items:
                continue
            out += [f"**{TYPE_LABEL[t]}**", ""]
            for p in sorted(items, key=lambda p: (["pt", "en"].index(p.lang), p.paraphrase)):
                tag = " ⛔" if p.article_blocked else ""
                orig = (" *(original pre-revision prompt, not logged as confirmed)*"
                        if p.paraphrase == 1 and key in ("aviao", "telefone") and p.lang == "en"
                        and t in ("F1", "F2", "F3") else "")
                out.append(f"- `{key}.{p.lang}.{t}.{p.paraphrase}` {p.text}{tag}{orig}")
                n_a += 1
            out.append("")
    head = out.index("## a. PT and EN prompts (`config/prompts.yaml`)")
    out.insert(head + 2, f"{n_a} prompts, grouped by fact and prompt type.")
    out.insert(head + 3, "")
    out += [
        "## b. Neutral baseline prompts, all languages (`config/baseline_prompts.yaml`)",
        "",
        f"Status `{baseline.status}`. Paraphrase *i* mirrors paraphrase *i* of the real prompts of the "
        "same type and language (same slot ending and ⛔ flag). Topics: names = *the novel / its author*, "
        "place = *the bridge*, artifact = *the first ship*. FR, DE and IT baseline blocks are still "
        "marked for native review (the native review covered `config/prompts.yaml`).",
        "",
    ]
    for t in TYPE_ORDER:
        items = [p for p in baseline.prompts if p.type == t]
        if not items:
            continue
        out += [f"### {TYPE_LABEL[t]}", ""]
        for lang in langs:
            for p in sorted((x for x in items if x.lang == lang), key=lambda x: x.paraphrase):
                rev = " *(native review pending)*" if p.needs_native_review else ""
                out.append(f"- `baseline.{lang}.{t}.{p.paraphrase}` {p.text}{' ⛔' if p.article_blocked else ''}{rev}")
        out.append("")
    out += [
        "## c. Forcing words for the article-confound test (`config/forcing.yaml`)",
        "",
        f"Status `{forcing.status}`. **Articles** trigger the test when the final layer's top token is "
        "one of them; **plural nouns** also trigger it and are forced as a second step after an article "
        "(*os → irmãos*); **contractions** replace the final preposition of ⛔ prompts, one pass per form.",
        "",
        "| Language | Articles | Plural nouns | Contractions |",
        "| --- | --- | --- | --- |",
    ]
    for lang in langs:
        pl = ", ".join(forcing.plural_for(lang)) or "—"
        co = "<br>".join(f"{k} → {', '.join(v)}" for k, v in forcing.contractions.get(lang, {}).items()) or "—"
        out.append(f"| `{lang}` | {', '.join(forcing.articles.get(lang, [])) or '—'} | {pl} | {co} |")
    out += [
        "",
        "## d. Behavioral surface forms, per candidate and language (`config/behavioral.yaml`)",
        "",
        f"Status `{behavioral.status}`. A candidate counts as mentioned in an answer when any of these "
        "forms appears as a whole word (case and accents ignored). The forms are shared across "
        "languages; a language column differs only where a form is excluded there (common word). "
        "First names alone never count.",
        "",
    ]
    for key, f in facts.items():
        out += [f"### `{key}`", "", "| Candidate | " + " | ".join(langs) + " |",
                "| --- |" + " --- |" * len(langs)]
        for c in f.candidates:
            cells = []
            for lang in langs:
                forms = behavioral.forms_for(key, c.id, lang)
                excl = (behavioral.forms[key][c.id].get("exclude") or {}).get(lang, [])
                cells.append(", ".join(forms) + (f" *(not alone: {', '.join(excl)})*" if excl else ""))
            out.append(f"| {c.label} (`{c.id}`) | " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out)


def main():
    exp, facts, prompts = load_experiment(), load_facts(), load_prompts()
    baseline = load_baseline()
    forcing  = load_forcing()
    OUT_FACTS.parent.mkdir(parents=True, exist_ok=True)
    OUT_FACTS.write_text(facts_doc(exp, facts), encoding="utf-8")
    OUT_PROMPTS.write_text(prompts_doc(exp, facts, prompts, baseline, forcing), encoding="utf-8")
    OUT_BEHAV.write_text(behavioral_doc(exp, facts, load_behavioral()), encoding="utf-8")
    OUT_PENDING.write_text(pending_doc(exp, facts, prompts, baseline, forcing, load_behavioral()),
                           encoding="utf-8")
    print(f"OK {OUT_FACTS}\nOK {OUT_PROMPTS}\nOK {OUT_BEHAV}\nOK {OUT_PENDING}")


if __name__ == "__main__":
    main()
