"""
scripts/make_review_doc.py
Gera os documentos de revisão a partir de config/*.yaml:

    reports/phase1_review.md   fatos, candidatos, stakes, nomes e
                               indicadores por idioma, com as notas do que
                               precisa de verificação
    reports/prompts_review.md  todos os prompts, por fato e idioma, com
                               as marcações (article_blocked, slot_case),
                               os prompts neutros da linha de base e as
                               palavras do teste do confundidor de artigo

    python scripts/make_review_doc.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from config.loader import (  # noqa: E402
    load_baseline, load_experiment, load_facts, load_forcing, load_prompts, prompts_for,
)

OUT_FACTS   = ROOT / "reports" / "phase1_review.md"
OUT_PROMPTS = ROOT / "reports" / "prompts_review.md"


def _names_cell(c, lang):
    by_case = c.names[lang]
    if list(by_case) == ["nom"]:
        return ", ".join(by_case["nom"])
    return "<br>".join(f"{case}: {', '.join(v)}" for case, v in by_case.items())


def facts_doc(exp, facts) -> str:
    langs = exp["languages"]
    out = [
        "# Phase 1 review: facts, candidates, names, indicators",
        "",
        "Generated by `scripts/make_review_doc.py` from `config/facts.yaml`. "
        "Edit the YAML, not this file. Every fact is `status: proposed` until you "
        "confirm it; runs refuse unconfirmed facts.",
        "",
        "Single names are the unit of measurement (one next-token distribution per position). "
        "Russian names are listed in the cases the prompts need (nom, gen, ins). "
        "Indicators are artifact names and places, no dates.",
        "",
    ]
    for key, f in facts.items():
        out += [f"## `{key}` ({f.kind}, verb: {f.verb}, status: {f.status})", ""]
        out += ["| Candidate | Dominant | Stakes |", "| --- | --- | --- |"]
        for c in f.candidates:
            st = ", ".join(f"{s.language} {s.type}" for s in c.stakes) or "—"
            out.append(f"| {c.label} (`{c.id}`) | {'yes' if c.dominant else ''} | {st} |")
        out += ["", "**Names**", "", "| Candidate | " + " | ".join(langs) + " |",
                "| --- |" + " --- |" * len(langs)]
        for c in f.candidates:
            out.append(f"| `{c.id}` | " + " | ".join(_names_cell(c, l) for l in langs) + " |")
        for t in f.indicator_types():
            out += ["", f"**Indicators: {t}**", "", "| Candidate | " + " | ".join(langs) + " |",
                    "| --- |" + " --- |" * len(langs)]
            for c in f.candidates:
                if c.indicators.get(t):
                    out.append(f"| `{c.id}` | " + " | ".join(
                        ", ".join(c.indicators_for(t, l)) for l in langs) + " |")
        notes = [(c.id, n) for c in f.candidates for n in c.notes]
        if notes:
            out += ["", "**To check**", ""] + [f"- `{cid}`: {n}" for cid, n in notes]
        out += [""]
    return "\n".join(out)


def _prompt_line(p) -> str:
    marks = (" ⛔" if p.article_blocked else "") + \
            (f" [{p.slot_case}]" if p.slot_case != "nom" else "")
    return f"- {p.type}.{p.paraphrase}: {p.text}{marks}"


def baseline_doc(exp, baseline) -> list:
    out = [
        "## Neutral baseline (`config/baseline_prompts.yaml`)",
        "",
        f"Status: `{baseline.status}`. Paraphrase *i* of each type mirrors paraphrase *i* of "
        "the real prompts in the same language (same slot ending, Russian case and ⛔ flag; "
        "the validator checks this). Topics: names = *the novel / its author*, "
        "place = *the bridge*, artifact = *the first ship*.",
        "",
    ]
    for lang in exp["languages"]:
        ps = prompts_for(baseline.prompts, None, lang)
        if not ps:
            continue
        flag = " (native review pending)" if ps[0].needs_native_review else ""
        out += [f"### {lang}{flag}", ""] + [_prompt_line(p) for p in ps] + [""]
    return out


def forcing_doc(exp, forcing) -> list:
    out = [
        "## Article-confound forcing words (`config/forcing.yaml`)",
        "",
        f"Status: `{forcing.status}`. **Articles** trigger the test when the final layer's top "
        "token is one of them; the word is appended and the candidates are measured at the next "
        "position. **Plural nouns** also trigger it, and are forced as a second step when they "
        "follow a forced article (*os → irmãos*). **Contractions** replace the final preposition "
        "of ⛔ prompts, one pass per form.",
        "",
        "| Language | Articles | Plural nouns | Contractions |",
        "| --- | --- | --- | --- |",
    ]
    for lang in exp["languages"]:
        plural = forcing.plural_nouns.get(lang, {})
        pl = ", ".join(plural.get("nom", [])) if list(plural) == ["nom"] else \
            "<br>".join(f"{c}: {', '.join(v)}" for c, v in plural.items())
        co = "<br>".join(f"{k} → {', '.join(v)}" for k, v in forcing.contractions.get(lang, {}).items())
        out.append(f"| {lang} | {', '.join(forcing.articles.get(lang, [])) or '—'} | "
                   f"{pl or '—'} | {co or '—'} |")
    return out + [""]


def prompts_doc(exp, facts, prompts, baseline=None, forcing=None) -> str:
    out = [
        "# Prompt review",
        "",
        "Generated from `config/prompts.yaml` (edit the YAML). Three paraphrases per type. "
        "Paraphrase 1 of F1–F3 for `aviao`/`telefone` in pt/en/de/it is the old prompt.",
        "",
        "- **⛔ article_blocked**: the slot ends in a preposition that contracts with an article "
        "(pt *por/em*, it *da/a*, fr *à*), so a candidate with an article (*os irmãos Wright*) "
        "cannot follow directly.",
        "- **[gen]/[ins]** (ru): grammatical case the slot requires; default nominative.",
        "- Native review pending for: " + ", ".join(exp["native_review_languages"]) + ". "
        "Set `needs_native_review: false` in the YAML once a native speaker has reviewed a block.",
        "",
    ]
    for key in facts:
        out += [f"## `{key}`", ""]
        for lang in exp["languages"]:
            ps = prompts_for(prompts, key, lang)
            if not ps:
                continue
            flag = " (native review pending)" if ps[0].needs_native_review else ""
            out += [f"### {lang}{flag}", ""]
            out += [_prompt_line(p) for p in ps] + [""]
    if baseline is not None:
        out += baseline_doc(exp, baseline)
    if forcing is not None:
        out += forcing_doc(exp, forcing)
    return "\n".join(out)


def main():
    exp, facts, prompts = load_experiment(), load_facts(), load_prompts()
    baseline = load_baseline()
    forcing  = load_forcing()
    OUT_FACTS.parent.mkdir(parents=True, exist_ok=True)
    OUT_FACTS.write_text(facts_doc(exp, facts), encoding="utf-8")
    OUT_PROMPTS.write_text(prompts_doc(exp, facts, prompts, baseline, forcing), encoding="utf-8")
    print(f"OK {OUT_FACTS}\nOK {OUT_PROMPTS}")


if __name__ == "__main__":
    main()
